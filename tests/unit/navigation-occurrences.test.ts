test('one manual occurrence never becomes a second launch while its retained experiment waits without another approval', () => {
  const session = createNavigationOccurrenceSession()
  session.advanceTo(2000)
  expect(session.requestOccurrence({ id: 'first', issuedAtMs: 2000, decision: 'approve' }).state).toBe('queued')
  let done = session.advanceTo(2020)
  for (let at = 3000; !done.terminal && at <= 110000; at += 1000) done = session.advanceTo(at)
  expect(done.mission.state).toBe('completed')
  expect(done.occurrences).toHaveLength(1)
  expect(done.occurrences[0]!.state).toBe('completed')
  expect(done.counts.armAccepted).toBe(1)
  expect(done.counts.engageAccepted).toBe(1)
  const waiting = session.advanceTo(done.nowMs + 2000)
  expect(waiting.occurrences).toEqual(done.occurrences)
  expect(waiting.trace).toEqual(done.trace)
  expect(waiting.terminal).toEqual(done.terminal)
  expect(waiting.counts.armAccepted).toBe(1)
  expect(waiting.counts.engageAccepted).toBe(1)
  expect(waiting.board.motorsN).toEqual([0, 0, 0, 0])
  expect(waiting.plant.motorsN.every(n => n < 0.01)).toBe(true)
  expect(waiting.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence).toBeGreaterThan(done.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence)
  expect(waiting.counts.controllerUpdates - done.counts.controllerUpdates).toBe(100)
  expect(waiting.horizonMs).toBe(180000)
})

import { replayMission, missionLimits } from '../../resources/functions/drone/missions/engine'

test('two fresh approvals execute two real missions with retained pose, raw and output sequences, controller and cumulative nominal energy', () => {
  const session = createNavigationOccurrenceSession()
  session.advanceTo(2000)
  session.requestOccurrence({ id: 'first', issuedAtMs: 2000, decision: 'approve' })
  let first = session.advanceTo(2020)
  for (let at = 3000; !first.terminal && at <= 110000; at += 1000) first = session.advanceTo(at)
  expect(first.mission.state).toBe('completed')
  const before = session.advanceTo(first.nowMs + 2000)
  expect(before.plant.groundContact).toBe(true)
  expect(before.plant.motorsN.every(n => n < 0.01)).toBe(true)
  expect(Math.hypot(before.estimate.localPosition!.positionM[0]!, before.estimate.localPosition!.positionM[1]!)).toBeLessThanOrEqual(0.2)
  const firstResult = before.occurrences[0]!.result
  expect(session.requestOccurrence({ id: 'second', issuedAtMs: before.nowMs, decision: 'approve' }).state).toBe('queued')
  const queued = session.snapshot()
  expect(queued.terminal).toEqual(before.terminal)
  expect(queued.trace).toEqual(before.trace)
  expect(queued.start).toEqual(before.start)
  expect(queued.board).toEqual(before.board)
  expect(queued.occurrences[1]!.binding).not.toBeNull()
  let second = session.advanceTo(before.nowMs + 20)
  expect(second.mission.state).toBe('running')
  expect(second.terminal).toBeNull()
  expect(second.occurrences[1]!.state).toBe('running')
  expect(second.trace.rows[0]!.action).toBe('start')
  expect(second.trace.rows[0]!.observation.nowMs).toBe(before.nowMs + 20)
  expect([...second.trace.rows[0]!.observation.positionM]).toEqual(second.estimate.localPosition!.positionM)
  expect(Math.hypot(second.trace.rows[0]!.observation.positionM[0], second.trace.rows[0]!.observation.positionM[1])).toBeGreaterThan(0.05)
  expect(second.estimate.resets).toEqual(before.estimate.resets)
  expect(second.board.bootId).toBe(before.board.bootId)
  expect(second.board.sequence).toBeGreaterThan(before.board.sequence)
  expect(second.authority.sequence).toBeGreaterThan(before.authority.sequence)
  expect(second.authority.epoch).toBeGreaterThan(before.authority.epoch)
  expect(second.counts.controllerUpdates - before.counts.controllerUpdates).toBe(1)
  expect(second.energy.usedWh).toBeGreaterThanOrEqual(before.energy.usedWh)
  expect(second.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence).toBeGreaterThan(before.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence)
  for (let at = before.nowMs + 1000; !second.terminal && at <= 170000; at += 1000) second = session.advanceTo(at)
  expect(second.mission.state).toBe('completed')
  const tail = session.advanceTo(second.nowMs + 2000)
  expect(tail.occurrences).toHaveLength(2)
  expect(tail.occurrences.map(item => item.state)).toEqual(['completed', 'completed'])
  expect(tail.occurrences[0]!.result).toEqual(firstResult)
  expect(tail.counts.armAccepted).toBe(2)
  expect(tail.counts.engageAccepted).toBe(2)
  expect(tail.energy.usedWh).toBeGreaterThan(before.energy.usedWh)
  expect(tail.plant.motorsN.every(n => n < 0.01)).toBe(true)
  for (const item of tail.occurrences) {
    expect(item.result!.trace.rows.length).toBeLessThanOrEqual(missionLimits.rows)
    expect(item.result!.metrics.precisionLandingErrorM).toBeLessThan(0.03)
    expect(item.result!.metrics.minTruthClearanceM).toBeGreaterThan(1)
    expect(replayMission(item.result!.trace).snapshot().state).toBe('completed')
  }
  const binding = tail.occurrences[0]!.binding
  expect(session.requestOccurrence({ id: 'first', issuedAtMs: tail.nowMs, decision: 'deny' })).toEqual({ state: 'refused', reason: 'occurrence-consumed' })
  expect(session.requestOccurrence({ id: 'third', issuedAtMs: tail.nowMs, decision: 'approve' })).toEqual({ state: 'refused', reason: 'occurrence-capacity' })
  tail.occurrences[0]!.binding = 'changed-by-caller'
  tail.occurrences[0]!.result!.finalTruthPositionM[0] = 99
  expect(session.snapshot().occurrences[0]!.binding).toBe(binding)
  expect(session.snapshot().occurrences[0]!.result).toEqual(firstResult)
  // eslint-disable-next-line no-console
  console.log(`NAVIGATION_TWO_OCCURRENCES ${JSON.stringify({ runtime: Bun.version, starts: tail.occurrences.map(item => item.startedAtMs), terminals: tail.occurrences.map(item => item.terminalAtMs), rows: tail.occurrences.map(item => item.result!.trace.rows.length), retainedSecondPositionM: second.trace.rows[0]!.observation.positionM, beforeSecondUsedWh: before.energy.usedWh, finalUsedWh: tail.energy.usedWh, rawSequence: tail.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence, boardSequence: tail.board.sequence, boot: String(tail.board.bootId), horizonMs: tail.horizonMs, evidence: 'one-retained-virtual-plant' })}`)
})

test('unhealthy call authority cannot adopt later health and a call-valid approval expires before its actual next arm tick', () => {
  const unhealthy = createNavigationOccurrenceSession()
  unhealthy.advanceTo(0)
  expect(unhealthy.requestOccurrence({ id: 'unhealthy', issuedAtMs: 0, decision: 'approve' })).toEqual({ state: 'refused', reason: 'unqualified-launch-observation' })
  const rejected = unhealthy.snapshot().occurrences[0]!
  expect(rejected.binding).toBeNull()
  expect(rejected.attemptedAtMs).toBeNull()
  const healthy = unhealthy.advanceTo(2000)
  expect(healthy.estimate.health.tilt).toBe(true)
  expect(healthy.occurrences[0]).toEqual(rejected)
  expect(unhealthy.requestOccurrence({ id: 'unhealthy', issuedAtMs: 2000, decision: 'approve' }).reason).toBe('occurrence-consumed')
  expect(unhealthy.advanceTo(2020).counts.armAccepted).toBe(0)
  const expiring = createNavigationOccurrenceSession()
  expiring.advanceTo(2000)
  expect(expiring.requestOccurrence({ id: 'expires-at-arm', issuedAtMs: 1904, decision: 'approve' }).state).toBe('queued')
  const callBinding = expiring.snapshot().occurrences[0]!.binding
  expect(callBinding).not.toBeNull()
  const after = expiring.advanceTo(2020)
  expect(after.occurrences[0]!.state).toBe('refused')
  expect(after.occurrences[0]!.reason).toBe('approval-expired')
  expect(after.occurrences[0]!.attemptedAtMs).toBe(2020)
  expect(after.occurrences[0]!.binding).toBe(callBinding)
  expect(after.mission.state).toBe('ready')
  expect(after.trace.rows).toHaveLength(0)
  expect(after.counts.armAccepted).toBe(0)
  expect(after.counts.engageAccepted).toBe(0)
  expect(after.board.motorsN).toEqual([0, 0, 0, 0])
  expect(expiring.requestOccurrence({ id: 'expires-at-arm', issuedAtMs: 2020, decision: 'approve' }).reason).toBe('occurrence-consumed')
  expect(expiring.advanceTo(4000).counts.armAccepted).toBe(0)
})

test('busy, denied, stale and future identities consume only their own bounded records without replacing the accepted request', () => {
  const queued = createNavigationOccurrenceSession()
  queued.advanceTo(2000)
  queued.requestOccurrence({ id: 'accepted', issuedAtMs: 2000, decision: 'approve' })
  const before = queued.snapshot()
  expect(queued.requestOccurrence({ id: 'early', issuedAtMs: 2000, decision: 'approve' }).reason).toBe('occurrence-busy')
  const after = queued.snapshot()
  expect(after.occurrences[0]).toEqual(before.occurrences[0])
  expect(after.start).toEqual(before.start)
  expect(after.mission).toEqual(before.mission)
  expect(after.terminal).toEqual(before.terminal)
  expect(after.board).toEqual(before.board)
  const running = queued.advanceTo(2020)
  expect(running.counts.armAccepted).toBe(1)
  expect(running.occurrences.map(item => item.state)).toEqual(['running', 'refused'])
  expect(queued.requestOccurrence({ id: 'early', issuedAtMs: 2020, decision: 'deny' }).reason).toBe('occurrence-consumed')
  expect(queued.requestOccurrence({ id: 'third', issuedAtMs: 2020, decision: 'approve' }).reason).toBe('occurrence-capacity')
  expect(queued.advanceTo(4000).counts.armAccepted).toBe(1)
  const active = createNavigationOccurrenceSession()
  active.advanceTo(2000)
  active.requestOccurrence({ id: 'flying', issuedAtMs: 2000, decision: 'approve' })
  const live = active.advanceTo(2020)
  expect(active.requestOccurrence({ id: 'overlap', issuedAtMs: 2020, decision: 'approve' }).reason).toBe('occurrence-busy')
  expect(active.snapshot().start).toEqual(live.start)
  expect(active.snapshot().trace).toEqual(live.trace)
  expect(active.snapshot().board).toEqual(live.board)
  expect(active.snapshot().occurrences[0]).toEqual(live.occurrences[0])
  for (const value of [{ decision: 'deny' as const, issuedAtMs: 2000, reason: 'operator-denied' }, { decision: 'approve' as const, issuedAtMs: 1800, reason: 'approval-expired-or-future' }, { decision: 'approve' as const, issuedAtMs: 2004, reason: 'approval-expired-or-future' }]) {
    const session = createNavigationOccurrenceSession()
    session.advanceTo(2000)
    expect(session.requestOccurrence({ id: 'refused', issuedAtMs: value.issuedAtMs, decision: value.decision }).reason).toBe(value.reason)
    const record = session.snapshot().occurrences[0]
    expect(session.advanceTo(3000).counts.armAccepted).toBe(0)
    expect(session.requestOccurrence({ id: 'refused', issuedAtMs: 3000, decision: 'approve' }).reason).toBe('occurrence-consumed')
    expect(session.requestOccurrence({ id: 'fresh', issuedAtMs: 3000, decision: 'approve' }).state).toBe('queued')
    const started = session.advanceTo(3020)
    expect(started.counts.armAccepted).toBe(1)
    expect(started.occurrences[0]).toEqual(record)
  }
})

