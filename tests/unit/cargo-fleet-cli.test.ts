import { expect, test } from 'bun:test'
import { command } from '@stacksjs/testing'

test('native Buddy runs the actual two-carrier delivery and prints a bounded custody and mass report', async () => {
  const result = await command(['cargo:fleet']).withTimeout(30000)
  expect(result.timedOut).toBe(false)
  expect(result.exitCode).toBe(0)
  const report = JSON.parse(result.stdout)
  expect(report.evidence).toBe('owned-cargo-fleet-simulation')
  expect(report.scenario).toBe('nominal')
  expect(report.status).toBe('completed')
  expect(report.physicalFlightEnabled).toBe(false)
  expect(report.identityAuthenticated).toBe(false)
  expect(report.source.scope).toEqual({ bootId: '101', sessionId: '201' })
  expect(report.receiver.scope).toEqual({ bootId: '102', sessionId: '202' })
  expect(report.receiver.intake.outcome).toBe('received')
  expect(report.receiver.delivery.outcome).toBe('received')
  expect(report.transfer.intake.massBeforeKg).toBe(1.5)
  expect(report.transfer.intake.massAfterKg).toBe(1.6)
  expect(report.ownership.finalMassKg).toBe(3.1)
  expect(report.source.energy.evidence).toBe('declared-mission-power-budget')
  expect(report.receiver.energy.marginAboveReserveWh).toBeGreaterThan(0)
  expect(report.receiver.energy.measured).toBe(false)
  expect(report.receiver.energy.electricalModel).toBe(false)
  expect(result.stdout.trim().split('\n')).toHaveLength(1)
  expect(Buffer.byteLength(result.stdout)).toBeLessThanOrEqual(16384)
}, 40000)

test('native fleet failures exit incomplete while retaining the actual parcel owner and withheld custody', async () => {
  for (const [scenario, owner, receiverMassKg] of [['receiver-host-loss-before-intake', 'station-actor', 1.5], ['intake-receipt-loss', 'receiver-body', 1.6]] as const) {
    const result = await command(['cargo:fleet', '--scenario', scenario]).withTimeout(30000)
    expect(result.timedOut).toBe(false)
    expect(result.exitCode).toBe(2)
    const report = JSON.parse(result.stdout)
    expect(report.status).toBe('unqualified')
    expect(report.ownership.owner).toBe(owner)
    expect(report.ownership.finalMassKg).toBe(3.1)
    expect(report.receiver.finalLoad.totalMassKg).toBe(receiverMassKg)
    expect(report.receiver.intake.outcome).toBe('uncertain')
    expect(report.receiver.delivery.outcome).toBe('not-released')
    expect(report.transfer.finalRelease).toBeNull()
    expect(Buffer.byteLength(result.stdout)).toBeLessThanOrEqual(16384)
    expect(report.receiver.board.actuators).toEqual([0, 0, 0, 0])
  }
  const invalid = await command(['cargo:fleet', '--scenario', 'unknown-private-marker']).withTimeout(30000)
  expect(invalid.exitCode).toBe(1)
  expect(invalid.stdout).toBe('')
  expect(invalid.stderr).toContain('Cargo fleet simulation unavailable')
  expect(invalid.stderr).not.toContain('unknown-private-marker')
}, 100000)

test('a receiver delivery cannot hide a source kill behind a successful fleet exit', async () => {
  const result = await command(['cargo:fleet', '--scenario', 'source-kill-after-station-receipt']).withTimeout(30000)
  expect(result.timedOut).toBe(false)
  expect(result.exitCode).toBe(2)
  const report = JSON.parse(result.stdout)
  expect(report.status).toBe('unqualified')
  expect(report.source.status).toBe('blocked')
  expect(report.receiver.status).toBe('completed')
  expect(report.receiver.delivery.outcome).toBe('received')
  expect(report.ownership.owner).toBe('final-parcel-actor')
  expect(report.ownership.finalMassKg).toBe(3.1)
  expect(report.source.board.actuators).toEqual([0, 0, 0, 0])
  expect(result.stderr).toBe('')
}, 40000)
