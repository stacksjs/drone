import { expect, test } from 'bun:test'
import { simulateCargoFleet } from '../../resources/functions/drone/cargo/fleet'

// Public fleet seam: two actual raw-sensor/estimator/authority sessions share a
// world clock. No mocked body, custody state, mechanism ACK or preloaded receiver.
test('one source parcel crosses the finite station into a live receiver and completes its second delivery', () => {
  const run = simulateCargoFleet()
  expect(run.evidence).toBe('owned-cargo-fleet-simulation')
  expect(run.physicalFlightEnabled).toBe(false)
  expect(run.identityAuthenticated).toBe(false)
  expect(run.status).toBe('completed')
  expect(run.source.runtime.status).toBe('completed')
  expect(run.receiver.runtime.status).toBe('completed')
  expect(run.source.initialLoad.properties.totalMassKg).toBe(1.6)
  expect(run.receiver.initialLoad.properties.totalMassKg).toBe(1.5)
  expect(run.receiver.initialLoad.properties.phase).toBe('awaiting')
  expect(run.source.runtime.board.bootId).toBe(101n)
  expect(run.receiver.runtime.board.bootId).toBe(102n)
  expect(run.source.runtime.authority.sessionId).toBe(201n)
  expect(run.receiver.runtime.authority.sessionId).toBe(202n)
  expect(run.transfer.sourceRelease!.event.outcome).toBe('separated')
  expect(run.transfer.stationDeparture!.outcome).toBe('departed')
  const intake = run.transfer.intake!
  expect(intake.attachment.outcome).toBe('attached')
  if (intake.attachment.outcome !== 'attached') throw new Error('Expected actual modeled intake')
  expect(intake.attachment.before.properties.totalMassKg).toBe(1.5)
  expect(intake.attachment.after.properties.totalMassKg).toBe(1.6)
  expect(intake.receiver.atMs).toBe(intake.source.atMs)
  expect(intake.receiver.policyAtMs).toBeGreaterThanOrEqual(intake.atMs - 20)
  expect(intake.receiver.authority.state).toBe('autonomous')
  expect(intake.receiver.authority.sessionId).toBe(202n)
  expect(intake.source.hostAvailable).toBe(true)
  expect(intake.source.reference.startsWith('101:')).toBe(true)
  expect(intake.receiver.reference.startsWith('102:')).toBe(true)
  expect(run.source.delivery.outcome).toBe('received')
  expect(run.receiver.intake.custody.outcome).toBe('received')
  expect(run.receiver.delivery.outcome).toBe('received')
  expect(run.receiver.intake.custody.acknowledgedAtMs!).toBeGreaterThan(intake.atMs)
  expect(run.receiver.intake.custody.receiptCapturedAtMs!).toBeGreaterThanOrEqual(intake.atMs)
  expect(run.receiver.finalLoad.properties.phase).toBe('separated')
  expect(run.receiver.finalLoad.properties.totalMassKg).toBe(1.5)
  expect(run.ownership.transitions.map(row => [row.from, row.to])).toEqual([
    ['source-body', 'station-actor'], ['station-actor', 'receiver-body'], ['receiver-body', 'final-parcel-actor'],
  ])
  expect(run.ownership.initialMassKg).toBe(3.1)
  expect(run.ownership.finalMassKg).toBe(3.1)
  expect(run.ownership.maximumMassErrorKg).toBeLessThan(1e-12)
  expect(run.ownership.samples).toBeGreaterThan(1000)
  expect(run.station!.ownedMassKg).toBe(0)
  expect(run.recipient!.ownedMassKg).toBe(.1)
  expect(run.recipient!.phase).toBe('held')
  expect(run.transfer.stationDeparture!.atMs).toBeGreaterThan(run.transfer.sourceRelease!.atMs + 1000)
})

test('receiver host loss after its grant but before actual intake retains the one parcel at the station', () => {
  const run = simulateCargoFleet({ scenario: 'receiver-host-loss-before-intake' })
  expect(run.status).toBe('unqualified')
  expect(run.source.runtime.status).toBe('completed')
  expect(run.source.delivery.outcome).toBe('received')
  expect(run.receiver.runtime.status).toBe('host-lost')
  expect(run.receiver.runtime.board.fault).toBe('output-lease-expired')
  expect(run.receiver.runtime.board.actuators).toEqual([0, 0, 0, 0])
  // The frozen supervisor snapshot alone still says autonomous. The physical
  // mechanism must also check actual same-epoch host availability and lease age.
  expect(run.receiver.runtime.authority.state).toBe('autonomous')
  expect(run.transfer.intake).toBeNull()
  expect(run.transfer.stationDeparture).toBeNull()
  expect(run.receiver.finalLoad.properties.phase).toBe('awaiting')
  expect(run.receiver.finalLoad.properties.totalMassKg).toBe(1.5)
  expect(run.receiver.intake.custody.outcome).toBe('uncertain')
  expect(run.receiver.delivery.outcome).toBe('not-released')
  expect(run.faultInjection!.triggeredAtMs).toBe(run.receiver.intake.custody.grantedAtMs! + 4)
  expect(run.receiver.runtime.path.at(-1)!.atMs).toBe(run.receiver.intake.custody.grantedAtMs!)
  expect(run.station!.phase).toBe('cancelled')
  expect(run.station!.ownedMassKg).toBe(.1)
  expect(run.recipient).toBeNull()
  expect(run.ownership.transitions.map(row => [row.from, row.to])).toEqual([['source-body', 'station-actor']])
  expect(run.ownership.finalMassKg).toBe(3.1)
  expect(run.ownership.maximumMassErrorKg).toBeLessThan(1e-12)
})

test('lost intake receipt keeps actual mass on the receiver and follows its counted alternate without claiming custody', () => {
  const run = simulateCargoFleet({ scenario: 'intake-receipt-loss' })
  expect(run.status).toBe('unqualified')
  expect(run.transfer.intake!.attachment.outcome).toBe('attached')
  expect(run.transfer.finalRelease).toBeNull()
  expect(run.receiver.intake.custody.outcome).toBe('uncertain')
  expect(run.receiver.intake.custody.receiptCapturedAtMs).toBeNull()
  expect(run.receiver.runtime.status).toBe('completed')
  expect(run.receiver.runtime.mission.reason).toBe('payload-diversion-landed')
  expect(run.receiver.runtime.mission.payloadFailure).toMatchObject({ taskId: 'intake', reason: 'uncertain', landingTaskId: 'alternate-land' })
  expect(run.receiver.finalLoad.properties.phase).toBe('attached')
  expect(run.receiver.finalLoad.properties.totalMassKg).toBe(1.6)
  expect(run.receiver.delivery.outcome).toBe('not-released')
  // The declared alternate accepts a 0.18 m radius, not centimetre accuracy.
  expect(Math.hypot(run.receiver.runtime.finalTruthPositionM[0] - 5, run.receiver.runtime.finalTruthPositionM[1] - 3)).toBeLessThanOrEqual(.18)
  expect(run.ownership.transitions.map(row => row.to)).toEqual(['station-actor', 'receiver-body'])
  expect(run.ownership.finalMassKg).toBe(3.1)
  expect(run.ownership.maximumMassErrorKg).toBeLessThan(1e-12)
  expect(run.station!.ownedMassKg).toBe(0)
  expect(run.recipient).toBeNull()
  expect(run.faultInjection!.triggeredAtMs!).toBeGreaterThanOrEqual(run.transfer.intake!.atMs)
  expect(run.receiver.intake.custody.grantedAtMs).toBe(run.transfer.intake!.grant.issuedAtMs)
})

test('fleet scenario admission rejects unknown fields and accessors before opening a world', () => {
  let invoked = false
  for (const input of [null, [], 'nominal', { scenario: 'unknown-private-marker' }, { scenario: undefined }, { physical: true }, { get scenario() { invoked = true; return 'nominal' } }]) expect(() => simulateCargoFleet(input)).toThrow('cargo-fleet-arguments')
  expect(invoked).toBe(false)
  expect(() => simulateCargoFleet({}, 'extra')).toThrow('cargo-fleet-arguments')
})

test('the receiving vehicle can lose its primary radio during station handling and finish on its own captured backup link', () => {
  const run = simulateCargoFleet({ scenario: 'receiver-primary-link-loss' })
  expect(run.status).toBe('completed')
  expect(run.receiver.intake.custody.outcome).toBe('received')
  expect(run.receiver.delivery.outcome).toBe('received')
  expect(run.source.links.scope).toEqual({ vehicleId: 'carrier-a', bootId: 101, sessionId: 201 })
  expect(run.receiver.links.scope).toEqual({ vehicleId: 'carrier-b', bootId: 102, sessionId: 202 })
  expect(run.source.links.selectedSource).toBe('primary')
  expect(run.receiver.links.selectedSource).toBe('backup')
  expect(run.receiver.links.latchedLoss).toBe(false)
  expect(run.receiver.linkEvents.some(row => row.selectedSource === 'backup')).toBe(true)
  expect(run.faultInjection!.triggeredAtMs!).toBeGreaterThanOrEqual(run.faultInjection!.anchoredAtMs!)
  expect(run.transfer.intake!.atMs).toBeGreaterThan(run.faultInjection!.triggeredAtMs!)
  expect(run.ownership.finalMassKg).toBe(3.1)
})

test('loss of both receiver radios expires its own authority and brakes station transport while the source continues', () => {
  const run = simulateCargoFleet({ scenario: 'receiver-both-links-loss' })
  expect(run.status).toBe('unqualified')
  expect(run.source.runtime.status).toBe('completed')
  expect(run.source.links.latchedLoss).toBe(false)
  expect(run.receiver.links.latchedLoss).toBe(true)
  expect(run.receiver.links.selectedSource).toBeNull()
  expect(run.receiver.runtime.status).toBe('blocked')
  expect(run.receiver.runtime.authority.state).toBe('failsafe')
  expect(run.receiver.runtime.authority.reason).toBe('link-loss')
  expect(run.receiver.runtime.board.actuators).toEqual([0, 0, 0, 0])
  expect(run.receiver.finalLoad.properties.phase).toBe('awaiting')
  expect(run.transfer.intake).toBeNull()
  expect(run.transfer.stationDeparture).toBeNull()
  expect(run.station!.phase).toBe('cancelled')
  expect(run.station!.startedAtMs).not.toBeNull()
  expect(run.station!.cancelRequestedAtMs!).toBeGreaterThanOrEqual(run.station!.startedAtMs!)
  expect(run.station!.stoppedAtMs!).toBeGreaterThanOrEqual(run.station!.cancelRequestedAtMs!)
  expect(run.station!.ownedMassKg).toBe(.1)
  expect(Math.hypot(...run.station!.parcel!.velocityMps)).toBe(0)
  expect(run.ownership.owner).toBe('station-actor')
  expect(run.ownership.finalMassKg).toBe(3.1)
})

test('a real receiver joint shift refuses stale rendezvous and the departed point falls without duplication', () => {
  const run = simulateCargoFleet({ scenario: 'receiver-joint-shift-before-intake' })
  expect(run.status).toBe('unqualified')
  expect(run.transfer.intake!.attachment).toEqual({ outcome: 'refused', reason: 'mount-not-coincident' })
  expect(run.receiver.finalLoad.properties.phase).toBe('awaiting')
  expect(run.receiver.finalLoad.properties.totalMassKg).toBe(1.5)
  expect(run.receiver.intake.custody.outcome).toBe('rejected')
  expect(run.receiver.intake.custody.mechanismAtMs).toBe(run.transfer.intake!.atMs)
  expect(run.receiver.runtime.mission.payloadFailure!.reason).toBe('rejected')
  expect(run.receiver.runtime.mission.reason).toBe('payload-diversion-landed')
  expect(run.transfer.finalRelease).toBeNull()
  expect(run.recipient).toBeNull()
  expect(run.station!.ownedMassKg).toBe(0)
  expect(run.loose!.ownedMassKg).toBe(.1)
  expect(run.loose!.phase).toBe('held')
  expect(run.loose!.parcel!.positionM[2]).toBe(0)
  expect(run.loose!.impact!.atMs).toBeGreaterThan(run.transfer.intake!.atMs)
  expect(run.ownership.owner).toBe('loose-parcel')
  expect(run.ownership.finalMassKg).toBe(3.1)
  expect(run.ownership.maximumMassErrorKg).toBeLessThan(1e-12)
})
