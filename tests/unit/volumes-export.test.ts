import type { SurfaceMetadata, VolumeRequest } from '../../resources/functions/drone/volumes/types'
import { afterEach, expect, test } from 'bun:test'
import { createHash } from 'node:crypto'
import { mkdtemp, readFile, rm, stat } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { writeVolumeDataset } from '../../resources/functions/drone/volumes/export'
import { importGridSurface, importPlySurface, parseVolumeRequest, surfaceSourceDigest } from '../../resources/functions/drone/volumes/import'

const directories: string[] = []
afterEach(async () => {
  for (const directory of directories.splice(0))
    await rm(directory, { recursive: true, force: true })
})
async function literalRequest(): Promise<VolumeRequest> {
  const text = 'NCOLS 3\nnrows 2\nxllcorner 0\nyllcorner 0\ncellsize 2\nNODATA_value -9999\n8 -9999 4\n-2 3 6\n'
  const metadata: SurfaceMetadata = {
    version: 1, id: 'literal-grid',
    reference: { horizontalCrs: { kind: 'engineering', id: 'LOCAL:test-yard', definition: 'A declared metre-based laboratory yard frame', coordinateEpoch: null }, axes: 'EAST_NORTH', horizontalUnit: 'metre', verticalDatum: { kind: 'engineering', id: 'yard-floor', definition: 'Laboratory floor reference elevation' }, verticalUnit: 'metre', elevationPositive: 'up' },
    provenance: { evidence: 'synthetic', sourceKind: 'analytic', sourceSha256: await surfaceSourceDigest(text), acquisition: { status: 'synthetic', sourceId: 'analytic-grid' }, reconstructionOrMeshing: { status: 'synthetic', sourceId: 'analytic-grid' }, boresightCalibration: { status: 'not-applicable', reportId: null }, timeCalibration: { status: 'not-applicable', reportId: null }, groundClassification: { status: 'unknown', description: 'Analytic elevations, no physical classification', reportId: null }, georeferencing: { verticalBoundM: 0.1, horizontalBoundM: null, reportId: 'analytic-height-bound' } },
  }
  return { version: 1, id: 'literal-export', surface: await importGridSurface(text, metadata), boundary: { outer: [[0, 0], [6, 0], [6, 4], [0, 4]], holes: [] }, base: { kind: 'plane', anchorM: [0, 0, 0], gradientEast: 0, gradientNorth: 0, assumption: 'A synthetic flat floor', evidence: 'synthetic', verticalBoundM: 0.2 }, reference: null }
}

test('exports independently reloadable numeric cells, bound metadata and auditable covered-domain results', async () => {
  const root = await mkdtemp(join(tmpdir(), 'drone-volume-export-'))
  directories.push(root)
  const request = await literalRequest()
  const output = await writeVolumeDataset(join(root, 'dataset'), request)
  const manifestText = await readFile(output.manifest, 'utf8')
  const manifest = JSON.parse(manifestText)
  expect(output.manifestSha256).toBe(createHash('sha256').update(manifestText).digest('hex'))
  expect(manifest.physicalAccuracyVerified).toBe(false)
  expect(manifest.acquisitionPerformed).toBe(false)
  expect(manifest.reconstructionPerformed).toBe(false)
  expect(manifest.originalSourceSha256).toBe(request.surface.metadata.provenance.sourceSha256)
  for (const file of manifest.files) {
    const bytes = await readFile(join(output.directory, file.path))
    expect(bytes.byteLength).toBe(file.bytes)
    expect(createHash('sha256').update(bytes).digest('hex')).toBe(file.sha256)
  }
  const source = await readFile(join(output.directory, 'surface.asc'), 'utf8')
  const sidecar = JSON.parse(await readFile(join(output.directory, 'surface.metadata.json'), 'utf8'))
  expect(sidecar.provenance.sourceSha256).toBe(await surfaceSourceDigest(source))
  expect(sidecar.provenance.sourceSha256).not.toBe(request.surface.metadata.provenance.sourceSha256)
  expect((await importGridSurface(source, sidecar)).geometry).toEqual(request.surface.geometry)
  const reloaded = parseVolumeRequest(await readFile(join(output.directory, 'request.json'), 'utf8'))
  expect(reloaded).toEqual(request)
  const report = JSON.parse(await readFile(output.report, 'utf8'))
  expect(report.signedTopMinusBaseM3).toBeCloseTo(76, 10)
  expect(report.aboveBaseM3).toBeCloseTo(84, 10)
  expect(report.belowBaseM3).toBeCloseTo(8, 10)
  expect(report.coveredAreaM2).toBeCloseTo(20, 10)
  expect(report.uncoveredAreaM2).toBeCloseTo(4, 10)
  expect(report.fullBoundarySignedM3).toBeNull()
  expect(report.physicalAccuracyVerified).toBe(false)
  const csv = await readFile(output.contributions, 'utf8')
  expect(csv.split('\n').filter(Boolean).length).toBe(report.integrationPieces.length + 1)
  expect(csv).toContain('signedTopMinusBaseM3')
  expect(csv).toContain('polygonEastNorthM')
  await expect(writeVolumeDataset(output.directory, request)).rejects.toThrow()
  expect(await readFile(output.manifest, 'utf8')).toBe(manifestText)
})


test('exports an actual indexed PLY surface and rebinds its sidecar to regenerated bytes', async () => {
  const root = await mkdtemp(join(tmpdir(), 'drone-volume-ply-'))
  directories.push(root)
  const request = await literalRequest()
  const original = 'ply\nformat ascii 1.0\ncomment Independently authored wedge\nelement vertex 4\nproperty float x\nproperty float y\nproperty float z\nelement face 2\nproperty list uchar int vertex_index\nend_header\n0 0 0\n4 0 4\n4 3 4\n0 3 0\n3 0 1 2\n3 0 2 3\n'
  const metadata = structuredClone(request.surface.metadata)
  metadata.provenance.sourceSha256 = await surfaceSourceDigest(original)
  request.surface = await importPlySurface(original, metadata)
  request.boundary.outer = [[0, 0], [4, 0], [4, 3], [0, 3]]
  const output = await writeVolumeDataset(join(root, 'mesh'), request)
  const source = await readFile(join(output.directory, 'surface.ply'), 'utf8')
  const sidecar = JSON.parse(await readFile(join(output.directory, 'surface.metadata.json'), 'utf8'))
  expect((await importPlySurface(source, sidecar)).geometry).toEqual(request.surface.geometry)
  expect(sidecar.provenance.sourceSha256).not.toBe(metadata.provenance.sourceSha256)
  const report = JSON.parse(await readFile(output.report, 'utf8'))
  expect(report.signedTopMinusBaseM3).toBeCloseTo(24, 10)
  expect(report.coveredAreaM2).toBeCloseTo(12, 10)
  expect(report.fullBoundarySignedM3).toBeCloseTo(24, 10)
  const manifest = JSON.parse(await readFile(output.manifest, 'utf8'))
  expect(manifest.sourcePath).toBe('surface.ply')
  expect(manifest.originalSourceSha256).toBe(metadata.provenance.sourceSha256)
})

test('invalid requests cannot publish a completion marker or create the requested dataset', async () => {
  const root = await mkdtemp(join(tmpdir(), 'drone-volume-invalid-'))
  directories.push(root)
  const request = await literalRequest()
  request.base = { kind: 'surface' } as unknown as VolumeRequest['base']
  const target = join(root, 'invalid')
  await expect(writeVolumeDataset(target, request)).rejects.toThrow()
  await expect(stat(target)).rejects.toThrow()
})
