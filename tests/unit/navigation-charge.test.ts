import { createChargePlant, chargeModel } from '../../resources/functions/drone/navigation/charge'

test('private charge plant integrates only completed intervals with eta and cancels a close superseded at the same epoch', () => {
  const plant = createChargePlant('nominal')
  plant.tick(0, 1, 2, 0)
  for (let at = 4; at <= 40; at += 4) plant.tick(at, 1, 0, 0)
  expect(plant.snapshot().relayClosed).toBe(true)
  expect(plant.snapshot().currentA).toBe(0)
  expect(plant.snapshot().grossGainWh).toBe(0)
  for (let at = 44; at <= 8000; at += 4) plant.tick(at, 1, 0, 0)
  const result = plant.snapshot()
  const seconds = (8000 - 40) / 1000
  const expected = .9 * 14.8 * (2 * seconds - 2 * .02 * (1 - Math.exp(-seconds / .02))) / 3600
  expect(result.grossGainWh).toBeCloseTo(expected, 12)
  expect(result.storedWh).toBeCloseTo(18 + expected, 10)
  expect(result.grossGainWh).toBeLessThan(.06)
  const canceled = createChargePlant('nominal')
  canceled.tick(0, 1, 0, 0)
  for (let at = 4; at <= 40; at += 4) canceled.tick(at, at === 40 ? 0 : 1, 0, 0)
  for (let at = 44; at <= 200; at += 4) canceled.tick(at, 0, 0, 0)
  expect(canceled.snapshot().relayClosed).toBe(false)
  expect(canceled.snapshot().grossGainWh).toBe(0)
  expect(chargeModel.eta).toBe(.9)
})

