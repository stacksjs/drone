import { expect, test } from 'bun:test'
import { createNavigationSession } from '../../resources/functions/drone/navigation/runtime'

test('retained navigation waits without an explicit start while real sensors and estimates advance', () => {
  const session = createNavigationSession()
  const initial = session.advanceTo(0)
  const waiting = session.advanceTo(2000)
  expect(waiting.lifecycle).toBe('waiting')
  expect(waiting.start.state).toBe('not-requested')
  expect(waiting.mission.state).toBe('ready')
  expect(waiting.trace.rows).toHaveLength(0)
  expect(waiting.counts.armAccepted).toBe(0)
  expect(waiting.counts.engageAccepted).toBe(0)
  expect(waiting.counts.nonzeroAcceptedFrames).toBe(0)
  expect(waiting.board.motorsN).toEqual([0, 0, 0, 0])
  expect(waiting.plant.motorsN).toEqual([0, 0, 0, 0])
  expect(waiting.plant.groundContact).toBe(true)
  expect(waiting.board.lastCheckedAtMs).toBe(2000)
  expect(waiting.sensors.nowMs).toBe(2000)
  expect(waiting.estimate.nowMs).toBe(2000)
  expect(waiting.estimate.health.tilt).toBe(true)
  expect(waiting.estimate.health.localPosition).toBe(true)
  expect(waiting.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence).toBeGreaterThan(initial.sensors.sensors.find(s => s.kind === 'imu')?.observation?.sequence ?? 0)
  expect(waiting.energy.usedWh).toBe(0)
})

import { replayMission } from '../../resources/functions/drone/missions/engine'

test('one delayed explicit start flies the owned route and preserves its terminal trace through an actual plant and sensor tail', () => {
  const session = createNavigationSession()
  const grounded = session.advanceTo(2000)
  expect(grounded.plant.groundContact).toBe(true)
  expect(grounded.plant.motorsN.every(n => n < 0.01)).toBe(true)
  expect(session.requestStart().state).toBe('queued')
  let current = session.advanceTo(2020)
  expect(current.start.state).toBe('started')
  expect(current.start.attemptedAtMs).toBe(2020)
  expect(current.counts.armAccepted).toBe(1)
  expect(current.counts.engageAccepted).toBe(1)
  expect(current.trace.rows[0]!.action).toBe('start')
  expect(current.trace.rows[0]!.observation.nowMs).toBe(2020)
  for (let at = 3000; !current.terminal && at <= 110000; at += 1000) current = session.advanceTo(at)
  expect(current.mission.state).toBe('completed')
  expect(current.counts.nonzeroAcceptedFrames).toBeGreaterThan(0)
  expect(current.terminal!.metrics.precisionLandingErrorM).toBeLessThan(0.03)
  expect(current.terminal!.metrics.minTruthClearanceM).toBeGreaterThan(1)
  expect(current.terminalPlant!.motorsN.some(n => n > 0.01)).toBe(true)
  const frozen = JSON.stringify(current.trace)
  const terminal = current.terminal
  const tail = session.advanceTo(current.nowMs + 2000)
  expect(tail.trace).toEqual(JSON.parse(frozen))
  expect(tail.terminal).toEqual(terminal)
  expect(replayMission(tail.trace).snapshot()).toEqual(tail.mission)
  expect(tail.nowMs).toBeGreaterThan(tail.terminalAtMs!)
  expect(tail.board.lastCheckedAtMs).toBe(tail.nowMs)
  expect(tail.sensors.nowMs).toBe(tail.nowMs)
  expect(tail.estimate.nowMs).toBe(tail.nowMs)
  expect(tail.estimate.bootId).toBe(55n)
  expect(tail.estimate.resets).toEqual(current.estimate.resets)
  expect(tail.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence).toBeGreaterThan(current.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence)
  expect(tail.plant.motorsN.every(n => n < 0.01)).toBe(true)
  expect(tail.board.motorsN).toEqual([0, 0, 0, 0])
  expect(tail.energy.usedWh).toBeGreaterThan(0)
  expect(tail.energy.usedWh).toBeGreaterThanOrEqual(current.energy.usedWh)
  // eslint-disable-next-line no-console
  console.log(`NAVIGATION_SESSION_TAIL ${JSON.stringify({ runtime: Bun.version, startAtMs: current.start.attemptedAtMs, terminalAtMs: current.terminalAtMs, tailAtMs: tail.nowMs, traceRows: tail.trace.rows.length, terminalMotorsN: current.terminalPlant!.motorsN, tailMotorsN: tail.plant.motorsN, estimateAtMs: tail.estimate.nowMs, rawImuSequence: tail.sensors.sensors.find(s => s.kind === 'imu')!.observation!.sequence, precisionM: tail.terminal!.metrics.precisionLandingErrorM, usedWh: tail.energy.usedWh, evidence: 'virtual-physics-only' })}`)
})

test('actual host silence preserves stale host state while independent output expiry and plant motor lag continue', () => {
  const session = createNavigationSession()
  session.advanceTo(2000)
  session.requestStart()
  let flying = session.advanceTo(2020)
  for (let at = 2040; flying.plant.positionM[2] >= -0.3 && at <= 6000; at += 20) flying = session.advanceTo(at)
  expect(flying.counts.nonzeroAcceptedFrames).toBeGreaterThan(0)
  expect(flying.plant.positionM[2]).toBeLessThan(-0.3)
  expect(flying.board.motorsN.some(n => n > 0)).toBe(true)
  const deadline = flying.board.expiresAtMs!
  expect(deadline - flying.nowMs).toBe(60)
  const silent = session.stopHost()
  expect(silent.hostAvailable).toBe(false)
  expect(silent.hostDataStale).toBe(true)
  expect(silent.board).toEqual(flying.board)
  expect(silent.authority).toEqual(flying.authority)
  const beforeExpiry = session.advanceTo(deadline - 4)
  expect(beforeExpiry.board.fault).toBeNull()
  expect(beforeExpiry.board.motorsN.some(n => n > 0)).toBe(true)
  const expired = session.advanceTo(deadline)
  expect(expired.board.fault).toBe('output-lease-expired')
  expect(expired.board.motorsN).toEqual([0, 0, 0, 0])
  expect(expired.lifecycle).toBe('recovery-required')
  const tail = session.advanceTo(deadline + 500)
  expect(tail.counts).toEqual(flying.counts)
  expect(tail.lastHostAtMs).toBe(flying.lastHostAtMs)
  expect(tail.estimate).toEqual(flying.estimate)
  expect(tail.sensors).toEqual(flying.sensors)
  expect(tail.trace).toEqual(flying.trace)
  expect(tail.mission.state).toBe('running')
  expect(tail.authority).toEqual(flying.authority)
  expect(tail.authority.state).toBe('autonomous')
  expect(tail.board.bootId).toBe(55n)
  expect(tail.board.sequence).toBe(flying.board.sequence)
  expect(tail.board.lastCheckedAtMs).toBe(deadline + 500)
  expect(tail.board.fault).toBe('output-lease-expired')
  expect(tail.plant.motorsN.every(n => n < 0.01)).toBe(true)
  expect(tail.plant.positionM).not.toEqual(flying.plant.positionM)
  expect(session.requestStart().state).toBe('refused')
  expect(session.advanceTo(deadline + 1000).lifecycle).toBe('recovery-required')
  // eslint-disable-next-line no-console
  console.log(`NAVIGATION_SESSION_HOST_SILENCE ${JSON.stringify({ runtime: Bun.version, lastHostAtMs: flying.lastHostAtMs, frameAtMs: flying.nowMs, deadlineMs: deadline, tailAtMs: tail.nowMs, hostUpdatesDelta: tail.counts.hostUpdates - flying.counts.hostUpdates, controllerUpdatesDelta: tail.counts.controllerUpdates - flying.counts.controllerUpdates, revokeDelta: tail.counts.boardRevokes - flying.counts.boardRevokes, boardFault: tail.board.fault, cachedAuthority: tail.authority.state, cachedMission: tail.mission.state, estimateAtMs: tail.estimate.nowMs, tailMotorsN: tail.plant.motorsN, evidence: 'virtual-physics-only' })}`)
})

test('host silence consumes a queued start before any authority attempt or mission row', () => {
  const session = createNavigationSession()
  const waiting = session.advanceTo(2000)
  expect(session.requestStart().state).toBe('queued')
  const silent = session.stopHost()
  expect(silent.start.state).toBe('refused')
  expect(silent.start.reason).toBe('host-unavailable-before-attempt')
  expect(silent.start.attemptedAtMs).toBeNull()
  const later = session.advanceTo(4000)
  expect(later.counts).toEqual(waiting.counts)
  expect(later.counts.armAccepted).toBe(0)
  expect(later.counts.engageAccepted).toBe(0)
  expect(later.counts.nonzeroAcceptedFrames).toBe(0)
  expect(later.board.motorsN).toEqual([0, 0, 0, 0])
  expect(later.trace.rows).toHaveLength(0)
  expect(later.estimate).toEqual(waiting.estimate)
  expect(later.hostDataStale).toBe(true)
  expect(session.requestStart()).toEqual({ state: 'refused', reason: 'host-unavailable' })
})

test('a range-loss terminal freezes mission evidence while its actual neutral sensor and motor tail continues', () => {
  const session = createNavigationSession({ scenario: 'range-loss' })
  session.advanceTo(2000)
  session.requestStart()
  const stopped = session.advanceTo(7000)
  expect(stopped.start.state).toBe('started')
  expect(stopped.mission.state).toBe('blocked')
  expect(stopped.navigation.state).toBe('blocked')
  expect(stopped.terminal).not.toBeNull()
  expect(stopped.counts.nonzeroAcceptedFrames).toBeGreaterThan(0)
  expect(stopped.board.motorsN).toEqual([0, 0, 0, 0])
  const tail = session.advanceTo(9000)
  expect(tail.terminal).toEqual(stopped.terminal)
  expect(tail.trace).toEqual(stopped.trace)
  expect(tail.mission).toEqual(stopped.mission)
  expect(tail.estimate.nowMs).toBe(9000)
  expect(tail.sensors.nowMs).toBe(9000)
  expect(tail.estimate.resets).toEqual(stopped.estimate.resets)
  expect(tail.board.lastCheckedAtMs).toBe(9000)
  expect(tail.board.motorsN).toEqual([0, 0, 0, 0])
  expect(tail.plant.motorsN.every(n => n < 0.01)).toBe(true)
  expect(tail.energy.usedWh).toBeGreaterThanOrEqual(stopped.energy.usedWh)
  expect(session.requestStart().state).toBe('refused')
})

test('a refused unqualified start stays consumed and copied observations cannot restore launch eligibility', () => {
  const session = createNavigationSession()
  session.advanceTo(0)
  expect(session.requestStart().state).toBe('queued')
  const refused = session.advanceTo(20)
  expect(refused.start.state).toBe('refused')
  expect(refused.start.attemptedAtMs).toBe(20)
  expect(refused.start.reason).toBe('estimator-loss')
  expect(refused.counts.armAccepted).toBe(0)
  refused.start.state = 'not-requested'
  refused.counts.armAccepted = 99
  refused.plant.positionM[0] = 99
  refused.board.motorsN[0] = 10
  const healthy = session.advanceTo(2000)
  expect(healthy.estimate.health.tilt).toBe(true)
  expect(healthy.start.state).toBe('refused')
  expect(healthy.counts.armAccepted).toBe(0)
  expect(healthy.plant.positionM[0]).toBe(0)
  expect(healthy.board.motorsN).toEqual([0, 0, 0, 0])
  expect(session.requestStart()).toEqual({ state: 'refused', reason: 'start-attempt-consumed' })
  expect(session.advanceTo(4000).counts.nonzeroAcceptedFrames).toBe(0)
  const valid = createNavigationSession()
  valid.advanceTo(2000)
  valid.requestStart()
  valid.advanceTo(2020)
  expect(valid.requestStart().state).toBe('refused')
  expect(valid.advanceTo(2040).counts.armAccepted).toBe(1)
})

test('invalid advance latches host absence without ticking a wrong clock and valid future ticks expire the retained frame', () => {
  for (const invalid of [NaN, Infinity, 1996, 2001, 120004]) {
    const session = createNavigationSession()
    session.advanceTo(2000)
    session.requestStart()
    const before = session.advanceTo(2020)
    expect(before.board.motorsN.some(n => n > 0)).toBe(true)
    expect(() => session.advanceTo(invalid)).toThrow(RangeError)
    const stopped = session.snapshot()
    expect(stopped.nowMs).toBe(2020)
    expect(stopped.hostAvailable).toBe(false)
    expect(stopped.hostDataStale).toBe(true)
    expect(stopped.hostUnavailableReason).toBe('invalid-session-clock')
    expect(stopped.lifecycle).toBe('recovery-required')
    expect(stopped.board).toEqual(before.board)
    expect(stopped.authority).toEqual(before.authority)
    expect(stopped.counts).toEqual(before.counts)
    expect(session.requestStart().state).toBe('refused')
    const expiry = session.advanceTo(before.board.expiresAtMs!)
    expect(expiry.board.fault).toBe('output-lease-expired')
    expect(expiry.board.motorsN).toEqual([0, 0, 0, 0])
    expect(expiry.counts).toEqual(before.counts)
    expect(expiry.estimate).toEqual(before.estimate)
    expect(expiry.board.bootId).toBe(55n)
  }
})

test('waiting is finite without filling mission trace capacity and too little remaining mission time cannot launch', () => {
  const session = createNavigationSession()
  const last = session.advanceTo(120000)
  expect(last.lifecycle).toBe('waiting')
  expect(last.trace.rows).toHaveLength(0)
  expect(last.energy.usedWh).toBe(0)
  expect(last.estimate.nowMs).toBe(120000)
  expect(last.estimate.health.tilt).toBe(true)
  expect(session.advanceTo(120000)).toEqual(last)
  expect(session.requestStart()).toEqual({ state: 'refused', reason: 'insufficient-session-time' })
  expect(session.snapshot().counts.armAccepted).toBe(0)
  expect(() => session.advanceTo(120004)).toThrow(RangeError)
  expect(session.snapshot().nowMs).toBe(120000)
  expect(session.snapshot().board.motorsN).toEqual([0, 0, 0, 0])
})
